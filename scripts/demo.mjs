const base = process.env.CLASP_URL ?? 'http://127.0.0.1:4173';
try {
  const response = await fetch(`${base}/api/state`);
  if (!response.ok) throw new Error(`Clasp server did not respond at ${base}`);
  const state = await response.json();
  console.log(`Clasp dashboard: ${base}`);
  console.log(`Google model: ${state.agent.model} (${state.agent.configured ? 'API key configured; requests use the real LLM' : 'unavailable; GOOGLE_API_KEY missing'})`);
  console.log(`Stripe: ${state.stripe.configured ? 'test key configured' : 'unavailable; STRIPE_SECRET_KEY must begin sk_test_'}`);
  console.log(`Vexo: ${state.hardware.vexo.name ?? `expecting Vexo-HACK-${String(state.hardware.vexo.expectedBandNumber).padStart(2, '0')}`} (${state.hardware.vexo.status})`);
  console.log(`Identity mode: ${state.identityMode}`);
  console.log(`Voice speaker verifier: ${state.biometrics.voiceSpeaker.status}`);
  console.log(`Polar PPG identity verifier: ${state.biometrics.polarPpg.status}`);
  console.log('');
  console.log(state.identityMode === 'development-simulation'
    ? 'The dashboard exposes an explicitly labeled development-only identity simulation.'
    : 'Biometric mode fails closed until both real voice-speaker and Polar PPG identity verifiers return fresh MATCH results for the same person.');
  console.log('No sensor events, biometric results, or payments were generated by this check.');
} catch (error) {
  console.error(error instanceof Error ? error.message : error);
  console.error('Start the server with: npm run dev');
  process.exitCode = 1;
}
